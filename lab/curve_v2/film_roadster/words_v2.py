"""Regenerate lab/motion/src/curve_v2/film/words.ts for the v2 narration (vo/v2/, built by vo_v2.py).

Segments whose take changed are transcribed again (whisper.cpp medium.en via lab/motion/scripts/transcribe.mjs); the
untouched ones keep their v1 word timings, so their cues can't drift. S9 is dropped (cut in v2).
  python3 words_v2.py
"""
import json, pathlib, re, subprocess

HERE = pathlib.Path(__file__).parent
MOTION = HERE.parents[1] / "motion"
TS = MOTION / "src" / "curve_v2" / "film" / "words.ts"
V2 = HERE / "vo" / "v2"
ORDER = ["S1", "S2", "S3", "b1", "S4", "b2", "S5", "S6", "S7", "S8", "END"]
CHANGED = {"S1", "S6", "S7", "b1", "b2", "END"}


def words(captions):
    """whisper tokens -> words: a token with a leading space starts a word, the rest ("'re", ".") join the last one."""
    out = []
    for t in captions:
        tx = t["text"]
        if tx.startswith(" ") or not out:
            out.append([tx.strip(), t["startMs"], t["endMs"]])
        else:
            out[-1][0] += tx
            out[-1][2] = t["endMs"]
    return [w for w in out if w[0]]


src = TS.read_text()
old = json.loads(re.search(r"WORDS: Record<string, \[string, number, number\]\[\]> = (\{.*?\});\n", src, re.S).group(1))
W, SEC = {}, {}
for seg in ORDER:
    mp3 = V2 / f"{seg}_t.mp3"
    SEC[seg] = round(float(subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", str(mp3)],
                                          capture_output=True, text=True, check=True).stdout), 2)
    if seg not in CHANGED:
        W[seg] = old[seg]
        continue
    wav, js = V2 / f"{seg}_16k.wav", V2 / f"{seg}_t.json"
    subprocess.run(["ffmpeg", "-loglevel", "error", "-y", "-i", str(mp3), "-ar", "16000", "-ac", "1", str(wav)], check=True)
    subprocess.run(["node", "scripts/transcribe.mjs", str(wav), str(js)], cwd=MOTION, check=True, capture_output=True)
    W[seg] = words(json.loads(js.read_text()))
    print(seg, SEC[seg], "s:", " ".join(w[0] for w in W[seg]))

TS.write_text(
    "// Word timings for the Roadster film narration (whisper medium.en on lab/curve_v2/film_roadster/vo/v2/<seg>_t.mp3).\n"
    "// [word, startMs, endMs]. Generated by lab/curve_v2/film_roadster/words_v2.py; regenerate if the narration changes.\n"
    f"export const WORDS: Record<string, [string, number, number][]> = {json.dumps(W, separators=(', ', ': '))};\n"
    f"export const VO_SECONDS: Record<string, number> = {json.dumps(SEC, separators=(', ', ': '))};\n")
print("->", TS)
